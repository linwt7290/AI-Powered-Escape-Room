export function phrase(key, values) {
  return {key, values};
}

export function translate(locale, message) {
  const {key, values} = typeof message === 'string' ? {key: message} : message;
  const template = locale === 'en' && Object.hasOwn(english, key) ? english[key] : key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (token, name) =>
    Object.hasOwn(values, name) ? translate(locale, String(values[name])) : token);
}
